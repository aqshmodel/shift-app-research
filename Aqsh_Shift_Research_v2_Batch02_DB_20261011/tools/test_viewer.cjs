// Run with the bundled Node runtime and NODE_PATH for its Playwright package.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.VIEWER_BROWSER_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];
 const stats=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../reports/research_stats.json'),'utf8'));
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve(__dirname,'../comparison.html'),{waitUntil:'domcontentloaded'});
 await page.waitForSelector('.card');
 assert.equal(await page.locator('.card').count(),50);
 assert.ok((await page.locator('header').innerText()).includes(`${stats.document_observations}文書観測`));
 const dataset=await page.evaluate(()=>JSON.parse(document.getElementById('dataset').textContent));
 const enriched=dataset.products.filter(p=>p.latest_batch_count>0).length;
 assert.equal(dataset.products.filter(p=>p.logo_url).length,50);
 assert.equal(dataset.products.filter(p=>p.logo_kind==='service').length,40);
 assert.equal(dataset.products.filter(p=>p.logo_kind==='company').length,10);
 assert.equal(await page.locator('.card [data-logo]').count(),50);
 await page.locator('#newonly').check();
 assert.equal(await page.locator('.card').count(),enriched);
 await page.locator('#newonly').uncheck();
 await page.locator('#region').selectOption('JP');
 assert.equal(await page.locator('.card').count(),28);
 await page.locator('#region').selectOption('US');
 assert.equal(await page.locator('.card').count(),22);
 await page.locator('#region').selectOption('');
 await page.locator('#search').fill('Nafty');
 assert.equal(await page.locator('.card').count(),1);
 await page.locator('[data-detail="OF-JP04"]').click();
 assert.match(await page.locator('#detail').innerText(),/リリース前/);
 assert.match(await page.locator('#detail').innerText(),/B03-20261011/);
 assert.ok(await page.locator('#detail a[href="https://nafty.app/care/"]').count()>0);
 await page.locator('[data-close="detail"]').click();
 await page.locator('#search').fill('');
 for(const id of ['OF-JP01','OF-JP04','OF-US19','OF-US20']) await page.locator(`[data-pick="${id}"]`).check();
 await page.locator('[data-pick="OF-JP03"]').click();
 assert.equal(await page.locator('[data-pick="OF-JP03"]').isChecked(),false);
 await page.locator('#compare').click();
 assert.equal(await page.locator('#comparison tbody tr').count(),40);
 assert.equal(await page.locator('#comparison thead th').count(),5);
 assert.match(await page.locator('#comparison').innerText(),/公開資料に相反する記述/);
 await page.locator('#clear').click();
 assert.equal(await page.locator('[data-pick]:checked').count(),0);
 await page.locator('#search').fill('Humanity');
 await page.locator('[data-detail="OF-US17"]').click();
 assert.match(await page.locator('#detail').innerText(),/3\.75/);
 assert.match(await page.locator('#detail').innerText(),/年契約/);
 assert.equal(dataset.observations.length,stats.document_observations);
 assert.equal(new Set(dataset.observations.map(o=>o.observation_id)).size,stats.document_observations);
 assert.ok(dataset.observations.every(o=>Array.isArray(o.evidence)));
 assert.match(await page.locator('#detail').innerText(),/分類訂正で採用対象外/);
 await page.locator('[data-close="detail"]').click();
 await page.locator('#search').fill('ほすぴタッチ');
 await page.locator('[data-detail="OF-JP13"]').click();
 assert.match(await page.locator('#detail').innerText(),/1000/);
 assert.match(await page.locator('#detail').innerText(),/300000/);
 assert.match(await page.locator('#detail').innerText(),/99\.45/);
 assert.match(await page.locator('#detail').innerText(),/ロゴ掲載元/);
 await page.evaluate(()=>document.querySelector('#detail [data-logo]').dispatchEvent(new Event('error')));
 assert.equal(await page.locator('#detail [data-logo]').isVisible(),false);
 assert.match(await page.locator('#detail h2').innerText(),/ほすぴタッチ/);
 assert.equal(errors.length,0,errors.join('\n'));
 await page.locator('[data-close="detail"]').click();
 await page.locator('[data-close="comparison"]').click();
 await page.locator('#search').fill('');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.resolve(__dirname,'../reports/viewer-desktop.png'),fullPage:false});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('.card').count(),50);
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.resolve(__dirname,'../reports/viewer-mobile.png'),fullPage:false});
 fs.writeFileSync(path.resolve(__dirname,'../reports/viewer_validation.json'),JSON.stringify({browser:'Google Chrome via Playwright',batch:stats.latest_batch,cards:50,enriched,domestic:28,overseas:22,comparisonRows:40,comparisonColumns:5,uniqueDocumentObservations:stats.document_observations,logos:50,serviceLogos:40,companyLogos:10,logoFailureFallback:'passed',classificationHistory:'passed',pageErrors:errors,viewports:[1440,390],status:'passed'},null,2));
 await browser.close();
 console.log('viewer checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
